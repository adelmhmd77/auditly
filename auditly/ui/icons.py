def _svg(name: str, color: str, width: float = 2.0) -> bytes:
    body = P.get(name, P["file"])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>').encode()


def render_svg(data: bytes, size: int) -> QPixmap:
    pm = QPixmap(size, size)
    pm.fill(Qt.transparent)
    r = QSvgRenderer(QByteArray(data))
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    r.render(p, QRectF(0, 0, size, size))
    p.end()
    return pm


@lru_cache(maxsize=512)
def icon(name: str, color: str = "#59636E", size: int = 18, active: str | None = None) -> QIcon:
    ic = QIcon()
    for scale in (1, 2):
        ic.addPixmap(render_svg(_svg(name, color), size * scale), QIcon.Normal, QIcon.Off)
        if active:
            ic.addPixmap(render_svg(_svg(name, active), size * scale), QIcon.Normal, QIcon.On)
            ic.addPixmap(render_svg(_svg(name, active), size * scale), QIcon.Active, QIcon.On)
    return ic


def logo_pixmap(size: int = 64) -> QPixmap:
    return render_svg(LOGO_SVG.encode(), size)


